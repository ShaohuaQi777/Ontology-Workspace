"""Platform semantic service Protocol; transport operation names map explicitly."""
from typing import Protocol, runtime_checkable
from .dto import (IngestRequest, IngestResult, ParseRequest, ParseResult, ExtractRequest,
                  ExtractionResult, GraphBuildRequest, GraphResult, OntologyRequest,
                  OntologyResult, SHACLRequest, ValidationResult, ReasoningRequest,
                  ReasoningResult, Capability)

OPERATION_MAP = {'ingest':'ingest','parse':'parse','extract':'extract','build_graph':'build_graph',
                 'import_ontology':'ontology:import','edit_ontology':'ontology:edit',
                 'generate_ontology':'ontology:generate','export':'ontology:export',
                 'validate':'validate_shacl','reason':'reason','capabilities':'capabilities',
                 'normalize':'extension:normalize','align':'extension:align','detect_conflicts':'extension:conflicts'}


@runtime_checkable
class SemanticBackend(Protocol):
    def ingest(self, request: IngestRequest) -> IngestResult: ...
    def parse(self, request: ParseRequest) -> ParseResult: ...
    def extract(self, request: ExtractRequest) -> ExtractionResult: ...
    def build_graph(self, request: GraphBuildRequest) -> GraphResult: ...
    def ontology(self, request: OntologyRequest) -> OntologyResult: ...
    def validate_shacl(self, request: SHACLRequest) -> ValidationResult: ...
    def reason(self, request: ReasoningRequest) -> ReasoningResult: ...
    def capabilities(self) -> list[Capability]: ...
